#!/bin/bash
# show_location_index.sh — 快速问题定位索引 (仅包含 xd IO/文件系统诊断工具)

cat << 'EOF'
## 快速问题定位索引 (存储/IO 专项)

---

### 🔴 故障：存储 IO 性能下降，响应慢/耗时长
**现象：** 应用层 IO 响应慢，不清楚耗时集中在块层哪个阶段（排队、下发硬件、等待完成）。
**推荐命令：** `xd_iolatency`
**定位步骤：**
1. 执行 `xd_iolatency -d <设备名>`，工具自动统计 IO 各阶段时延分布。
2. 对比各阶段耗时：
   - **排队时延高 (G2I/I2D)** → 系统 IO 调度拥堵，考虑调整调度策略或降低并发。
   - **下发硬件后时延高 (D2C)** → 设备本身性能问题，检查磁盘健康状态。

---

### 🔴 故障：文件系统变只读 / SCSI 命令超时
**现象：** 文件系统突然变为只读，日志中出现 SCSI error，需要抓取具体失败命令及返回码。
**推荐命令：** `xd_scsiiotrace`
**定位步骤：**
1. 执行只抓错误命令模式：`xd_scsiiotrace -r`。
2. 复现或等待问题触发，查看输出的 `DISPOSITION` 字段：
   - `TIMEOUT_ERROR` → 命令超时，设备或链路异常。
   - `NEEDS_RETRY` → 设备返回需重试，可能存在介质错误。
3. 记录失败命令的十六进制返回码，用 `-p` 解析具体含义。

---

### 🔴 故障：SSD 写放大，定位高频写 IO 命令类型
**现象：** SSD 写入量远超应用预期，怀疑某类 IO 命令导致写放大，需统计命令类型分布。
**推荐命令：** `xd_scsiiocount`
**定位步骤：**
1. 执行统计，每 10 秒输出一次：`xd_scsiiocount -d <设备名> -i 10`。
2. 查看各 IO 命令（READ / WRITE / 其他）的数量占比，判断是否写命令异常集中。
3. 若写命令过多，进一步使用 `xd_ext4fsstat` 定位到具体写入文件。

---

### 🔴 故障：SSD 写放大，定位具体高流量写入文件/进程
**现象：** 磁盘写入量异常高，已确认是文件系统层写入问题，需精确到哪个文件/进程在大量写入。
**推荐命令：** `xd_ext4fsstat`
**定位步骤：**
1. 按写入量排序，全局统计：`xd_ext4fsstat -o w -s w -i 10`。
2. 切换到 PID 视角，确认对应写入进程：`xd_ext4fsstat -o w -s w -v p`。
3. 找到来源进程后，评估是否属于异常写入（如日志疯狂滚动、核心转储等）。

EOF
