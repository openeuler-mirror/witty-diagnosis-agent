1. **数据精简清晰**：输出内容必须简明扼要，优先使用**列表 (List)** 形式呈现关键信息。
2. **禁止冗余与自言自语**：只输出对用户有价值的必要内容。**严禁**将模型的输入（如用户的原始描述等）在输出中重新复述一次；**严禁**输出模型的内部思考过程、反思或自言自语。
